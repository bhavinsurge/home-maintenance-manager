"use client";

import { useEffect, useState } from "react";
import { AppShell } from "@/components/layout/app-shell";
import {
  Alert,
  Badge,
  Button,
  Card,
  EmptyState,
  PageHeader,
  Spinner,
} from "@/components/ui/primitives";
import { api, ApiClientError } from "@/lib/api-client";
import { formatDateTime } from "@/lib/utils/cn";
import Link from "next/link";

type Notification = {
  id: string;
  type: string;
  title: string;
  body: string;
  linkPath: string | null;
  readAt: string | null;
  createdAt: string;
};

export default function NotificationsPage() {
  const [items, setItems] = useState<Notification[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  async function load() {
    setLoading(true);
    try {
      const data = await api<{ items: Notification[] }>("/api/notifications?pageSize=50");
      setItems(data.items);
    } catch (err) {
      setError(err instanceof ApiClientError ? err.message : "Failed to load notifications");
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect -- intentional remote fetch on mount
    void load();
  }, []);

  async function markAll() {
    await api("/api/notifications/read-all", { method: "POST" });
    await load();
  }

  async function markOne(id: string) {
    await api(`/api/notifications/${id}/read`, { method: "POST" });
    await load();
  }

  return (
    <AppShell>
      <PageHeader
        title="Notifications"
        description="Maintenance reminders and warranty alerts generated by the worker."
        actions={
          <Button variant="secondary" onClick={() => void markAll()}>
            Mark all read
          </Button>
        }
      />
      {loading ? (
        <div className="flex justify-center py-16">
          <Spinner className="h-8 w-8" />
        </div>
      ) : error ? (
        <Alert>{error}</Alert>
      ) : items.length === 0 ? (
        <EmptyState
          title="Inbox clear"
          description="When schedules are due or warranties expire soon, reminders appear here."
        />
      ) : (
        <div className="space-y-3">
          {items.map((n) => (
            <Card key={n.id} className={n.readAt ? "opacity-70" : ""}>
              <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
                <div>
                  <div className="mb-2 flex flex-wrap gap-2">
                    <Badge tone={n.readAt ? "neutral" : "brand"}>{n.type}</Badge>
                    <span className="text-sm text-[var(--ink-muted)]">
                      {formatDateTime(n.createdAt)}
                    </span>
                  </div>
                  <h2 className="text-xl">{n.title}</h2>
                  <p className="mt-1 text-[var(--ink-muted)]">{n.body}</p>
                  {n.linkPath ? (
                    <Link
                      className="mt-2 inline-block text-sm font-semibold text-[var(--brand)]"
                      href={n.linkPath}
                    >
                      Open related asset
                    </Link>
                  ) : null}
                </div>
                {!n.readAt ? (
                  <Button size="sm" variant="secondary" onClick={() => void markOne(n.id)}>
                    Mark read
                  </Button>
                ) : null}
              </div>
            </Card>
          ))}
        </div>
      )}
    </AppShell>
  );
}
